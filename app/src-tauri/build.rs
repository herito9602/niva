fn main() {
    // `CARGO_CFG_DEBUG_ASSERTIONS` is set by cargo exactly when the crate being
    // built has `cfg(debug_assertions)`, the same switch that compiles
    // `mod debug` and `debug_dispatch` in or out. (`cfg!` here would describe
    // the build script itself, and `PROFILE` ignores `debug-assertions`
    // overrides.)
    let debug_build = std::env::var_os("CARGO_CFG_DEBUG_ASSERTIONS").is_some();

    // Release: only `capabilities/` is loaded and no `debug_dispatch`
    // permission exists. Debug: `capabilities-debug/` is loaded too. Both have
    // the text window's `submit_text` command (PR 2d-a).
    let mut attributes = tauri_build::Attributes::new();
    if debug_build {
        attributes = attributes
            .capabilities_path_pattern("./capabilities*/**/*")
            .app_manifest(
                tauri_build::AppManifest::new().commands(&["debug_dispatch", "submit_text"]),
            );
    } else {
        // `permissions/autogenerated/` is written by debug builds and, by
        // default, globbed into the app ACL of every later build (and
        // `commands()` makes tauri-build glob it too). The release defines its
        // one permission from a checked-in file in its own directory instead,
        // which keeps a stale `allow-debug-dispatch` out of the release binary.
        attributes = attributes
            .capabilities_path_pattern("./capabilities/**/*")
            .app_manifest(
                tauri_build::AppManifest::new()
                    .permissions_path_pattern("./permissions-release/**/*"),
            );
    }
    // A custom pattern disables tauri-build's own watch of the directory.
    println!("cargo:rerun-if-changed=capabilities");
    println!("cargo:rerun-if-changed=capabilities-debug");
    println!("cargo:rerun-if-changed=permissions-release");
    tauri_build::try_build(attributes).expect("failed to run tauri-build");
}
