/// How often the index is rebuilt.
pub const REFRESH_EVERY: Duration = Duration::from_secs(10 * 60);
/// The first retry after a failed build; each further failure doubles it up to
/// [`MAX_RETRY_DELAY`] (a dead PowerShell is not respawned every 30 s forever).
const RETRY_AFTER_FAILURE: Duration = Duration::from_secs(30);
const MAX_RETRY_DELAY: Duration = Duration::from_secs(10 * 60);
/// A miss never rebuilds more often than this (each build spawns PowerShell).
#[cfg(windows)]
const MIN_REBUILD_GAP: Duration = Duration::from_secs(30);

/// The wait before the next retry: 30 s after a first failure, then doubled,
/// capped at 10 minutes. `previous` is the last wait, `None` after a success.
pub fn next_retry_delay(previous: Option<Duration>) -> Duration {
    match previous {
        None => RETRY_AFTER_FAILURE,
        Some(delay) => (delay * 2).min(MAX_RETRY_DELAY),
    }
}

/// One index build. Returns how long to wait before the next one and keeps the
/// failure backoff in `backoff`.
pub fn refresh_step(
    index: &AppIndex,
    source: &dyn AppSource,
    backoff: &mut Option<Duration>,
) -> Duration {
    match index.refresh_from(source) {
        Ok(count) => {
            *backoff = None;
            eprintln!("[niva] app index: {count} apps");
            REFRESH_EVERY
        }
        Err(why) => {
            let wait = next_retry_delay(*backoff);
            *backoff = Some(wait);
            eprintln!("[niva] app index failed: {why}; retrying in {wait:?}");
            wait
        }
    }
}

/// The Windows PowerShell executable, from `SystemRoot`. `None` (fail closed)
/// when it is unset or empty: never a bare `powershell.exe`, which the OS would
/// resolve through the current directory and PATH.
pub fn powershell_path(system_root: Option<std::ffi::OsString>) -> Option<std::path::PathBuf> {
    let root = system_root.filter(|root| !root.is_empty())?;
    Some(std::path::PathBuf::from(root).join(r"System32\WindowsPowerShell\v1.0\powershell.exe"))
}
/// `Get-StartApps` takes about 4 s; a hung PowerShell is killed after this.
#[cfg(windows)]
const POWERSHELL_TIMEOUT: Duration = Duration::from_secs(45);

/// A fixed script: nothing from the model or the user is ever put into it.
#[cfg(windows)]
const START_APPS_SCRIPT: &str = "[Console]::OutputEncoding = [System.Text.Encoding]::UTF8; \
     Get-StartApps | Select-Object Name, AppID | ConvertTo-Json -Compress";

/// The Start menu through `Get-StartApps` (UWP apps included).
#[cfg(windows)]
pub struct PowerShellSource;

#[cfg(windows)]
impl AppSource for PowerShellSource {
    fn list(&self) -> Result<Vec<AppEntry>, String> {
        use std::io::Read;
        use std::os::windows::process::CommandExt;
        use std::process::{Command, Stdio};

        const CREATE_NO_WINDOW: u32 = 0x0800_0000;
        let exe = powershell_path(std::env::var_os("SystemRoot"))
            .ok_or("SystemRoot is not set: PowerShell is not started")?;
        let mut child = Command::new(exe)
            .args([
                "-NoProfile",
                "-NonInteractive",
                "-ExecutionPolicy",
                "Bypass",
            ])
            .arg("-Command")
            .arg(START_APPS_SCRIPT)
            .stdin(Stdio::null())
            .stdout(Stdio::piped())
            .stderr(Stdio::null())
            .creation_flags(CREATE_NO_WINDOW)
            .spawn()
            .map_err(|why| format!("could not start PowerShell: {why}"))?;
        let mut stdout = child.stdout.take().ok_or("no PowerShell output pipe")?;
        let (tx, rx) = std::sync::mpsc::channel();
        std::thread::spawn(move || {
            let mut bytes = Vec::new();
            let _ = tx.send(stdout.read_to_end(&mut bytes).map(|_| bytes));
        });
        let outcome = rx.recv_timeout(POWERSHELL_TIMEOUT);
        if outcome.is_err() {
            let _ = child.kill();
        }
        let _ = child.wait();
        let bytes = outcome
            .map_err(|_| "PowerShell did not answer in time".to_string())?
            .map_err(|why| format!("could not read PowerShell output: {why}"))?;
        parse_start_apps(&String::from_utf8_lossy(&bytes))
    }
}

/// Starts a target with `ShellExecuteExW` on the calling (worker) thread.
#[cfg(windows)]
pub struct ShellLauncher;

#[cfg(windows)]
impl Launcher for ShellLauncher {
    fn launch(&self, target: &str) -> Result<(), String> {
        use windows_sys::Win32::Foundation::GetLastError;
        use windows_sys::Win32::UI::Shell::{
            SEE_MASK_FLAG_NO_UI, SEE_MASK_NOASYNC, SHELLEXECUTEINFOW, ShellExecuteExW,
        };
        use windows_sys::Win32::UI::WindowsAndMessaging::SW_SHOWNORMAL;

        let wide: Vec<u16> = target.encode_utf16().chain(std::iter::once(0)).collect();
        // ShellExecute wants COM initialised on the calling thread; pool
        // workers have none, so each call brackets its own.
        let _com = super::com::ComGuard::apartment();
        // SAFETY: the struct is plain data; zeroed is a valid empty value, and
        // `cbSize` is set as the API requires.
        let mut info: SHELLEXECUTEINFOW = unsafe { std::mem::zeroed() };
        info.cbSize = std::mem::size_of::<SHELLEXECUTEINFOW>() as u32;
        // NO_UI: a dead entry reports an error instead of raising a modal
        // "cannot find" dialog that would hang this worker. NOASYNC: the call
        // finishes on this thread, which may not outlive a background one.
        info.fMask = SEE_MASK_FLAG_NO_UI | SEE_MASK_NOASYNC;
        info.lpFile = wide.as_ptr();
        info.nShow = SW_SHOWNORMAL;
        // SAFETY: `info` is initialised, `wide` is NUL-terminated and outlives
        // the call, and every other pointer in the struct is null.
        let ok = unsafe { ShellExecuteExW(&mut info) };
        if ok != 0 {
            Ok(())
        } else {
            // SAFETY: reads the calling thread's last error.
            Err(format!("ShellExecuteExW failed (error {})", unsafe {
                GetLastError()
            }))
        }
    }
}

/// `open_app` and `running_processes` on the real system.
#[cfg(windows)]
pub struct WinApps {
    apps: Apps,
    index: Arc<AppIndex>,
}

#[cfg(windows)]
impl WinApps {
    /// Builds the index in the background (the first command may still find it
    /// not ready) and keeps it fresh.
    pub fn start() -> Self {
        let this = Self::without_index();
        let index = this.index.clone();
        std::thread::Builder::new()
            .name("niva-app-index".into())
            .spawn(move || keep_fresh(&index, &PowerShellSource))
            .map(drop)
            .unwrap_or_else(|why| eprintln!("[niva] could not start the app indexer: {why}"));
        this
    }

    /// No background indexer: `open` stays not ready. For the process list and
    /// for tests.
    pub fn without_index() -> Self {
        let index = Arc::new(AppIndex::new());
        WinApps {
            apps: Apps::new(index.clone(), Arc::new(ShellLauncher)),
            index,
        }
    }

    pub fn is_ready(&self) -> bool {
        self.index.is_ready()
    }

    pub fn open(&self, name: &str) -> Result<String, PcError> {
        self.apps.open(name)
    }

    /// Every process in the ToolHelp snapshot. An unreadable snapshot is an
    /// error, never an empty list: `close_app` must not read "nothing is
    /// running" from a failure.
    pub fn running_processes(&self) -> Result<Vec<ProcessInfo>, PcError> {
        snapshot().map(|all| all.iter().map(ProcessEntry::info).collect())
    }

    /// Asks the windows of `exe` to close (see `win_close`).
    pub fn close(&self, exe: &str) -> Result<CloseOutcome, PcError> {
        super::win_close::close(exe)
    }
}

/// Builds the index, then rebuilds it on a timer and after a miss.
#[cfg(windows)]
fn keep_fresh(index: &AppIndex, source: &dyn AppSource) {
    let mut backoff = None;
    loop {
        let started = std::time::Instant::now();
        let wait = refresh_step(index, source, &mut backoff);
        if index.refresh.wait(wait) {
            // Woken by a miss: do not rebuild more often than the gap.
            if let Some(rest) = MIN_REBUILD_GAP.checked_sub(started.elapsed()) {
                std::thread::sleep(rest);
            }
        }
    }
}

#[cfg(windows)]
pub(super) fn snapshot() -> Result<Vec<ProcessEntry>, PcError> {
    use windows_sys::Win32::Foundation::{CloseHandle, INVALID_HANDLE_VALUE};
    use windows_sys::Win32::System::Diagnostics::ToolHelp::{
        CreateToolhelp32Snapshot, PROCESSENTRY32W, Process32FirstW, Process32NextW,
        TH32CS_SNAPPROCESS,
    };
    use windows_sys::Win32::System::RemoteDesktop::ProcessIdToSessionId;
    use windows_sys::Win32::System::Threading::GetCurrentProcessId;

    fn session_of(pid: u32) -> Option<u32> {
        let mut session = 0u32;
        // SAFETY: `session` is a valid out pointer for the call.
        (unsafe { ProcessIdToSessionId(pid, &mut session) } != 0).then_some(session)
    }

    // SAFETY: plain ToolHelp calls; the handle is closed below and the entry is
    // a zeroed plain-data struct whose `dwSize` is set as the API requires.
    unsafe {
        let handle = CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS, 0);
        if handle == INVALID_HANDLE_VALUE {
            return Err(PcError::Failed(format!(
                "could not read the process list (error {})",
                windows_sys::Win32::Foundation::GetLastError()
            )));
        }
        let own = session_of(GetCurrentProcessId());
        let mut entry: PROCESSENTRY32W = std::mem::zeroed();
        entry.dwSize = std::mem::size_of::<PROCESSENTRY32W>() as u32;
        let mut processes = Vec::new();
        let mut more = Process32FirstW(handle, &mut entry) != 0;
        if !more {
            let error = windows_sys::Win32::Foundation::GetLastError();
            CloseHandle(handle);
            return Err(PcError::Failed(format!(
                "the process list is empty or unreadable (error {error})"
            )));
        }
        while more {
            processes.push(process_entry(
                entry.th32ProcessID,
                &entry.szExeFile,
                session_of(entry.th32ProcessID),
                own,
            ));
            more = Process32NextW(handle, &mut entry) != 0;
        }
        CloseHandle(handle);
        Ok(processes)
    }
}
