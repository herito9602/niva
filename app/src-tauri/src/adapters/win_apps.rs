//! `open_app` and `running_processes` for Windows (spec `pc-actions`, design
//! "Safety Gate": the app index lifecycle).
//!
//! - The app index is the Start menu as `Get-StartApps` lists it (name + AppID,
//!   UWP apps included). It is built in the background, so a command before it
//!   is ready gets [`PcError::NotReady`] instead of a wait, and refreshed on a
//!   timer and after a miss. The action path never blocks on a rebuild.
//! - `open_app` matches the model's name against the index, fuzzily (it is a
//!   Safe tool: a wrong guess is harmless), then starts the INDEXED target with
//!   `ShellExecuteExW` (no UI, no async) and returns the launched entry's
//!   display name. The model's text is only ever compared with index names (and
//!   with the Spanish/English names of a built-in app, see [`aliases`]): it
//!   is never part of a command line, a path or a shell string. `open_app` has
//!   no confirmation, so the index holds launchable apps only (an allow-list,
//!   see [`is_launchable_id`]) and no uninstallers.
//! - `running_processes` is the ToolHelp snapshot; the core applies the
//!   protected list and the session filter.
//!
//! Everything that decides something is a pure function or sits behind a small
//! trait ([`AppSource`], [`Launcher`]) so it is tested with fakes. The Windows
//! calls are in the `cfg(windows)` part at the end.

use std::sync::{Arc, Condvar, Mutex};
use std::time::Duration;

