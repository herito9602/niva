/// One Start menu entry.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AppEntry {
    /// Display name, in the user's language (`Calculadora`, `Bloc de notas`).
    pub name: String,
    /// The AppID `Get-StartApps` reports: an AUMID for Store apps, a path or a
    /// known-folder id for desktop apps. System data, never model data.
    pub id: String,
}

/// `true` for an AppID that names something `open_app` may start: a packaged
/// app or a desktop AUMID (an identifier, see [`is_aumid`]) or an `.exe` target
/// (see [`is_exe_target`]). An ALLOW-list on purpose: `open_app` has no
/// confirmation, and `Get-StartApps` also lists scripts (`.cmd`), URLs
/// (`https://`), `.url` shortcuts, documents (`.pdf`, `.chm`, `.html`, `.txt`),
/// settings files (`.ini`), folders, shell locations (`::{GUID}`) and
/// shortcuts with arguments (`Microsoft.AutoGenerated.{GUID}`). Anything that
/// is not one of the two shapes is not launchable.
pub fn is_launchable_id(id: &str) -> bool {
    is_exe_target(id) || is_aumid(id)
}

/// An Application User Model ID: `Family_publisher!App` for a packaged app, or a
/// bare identifier for a desktop app (`Chrome`, `MSEdge`, `308046B0AF4A39CB`,
/// `com.squirrel.Discord.Discord`, `Microsoft.Office.WINWORD.EXE.15`). Letters,
/// digits and `. _ - ! ;` only: no path, drive, scheme, space or brace.
/// `Microsoft.AutoGenerated.{GUID}` is how Windows names a shortcut that has no
/// AUMID of its own (it may carry arguments or point at a script): not accepted.
fn is_aumid(id: &str) -> bool {
    let allowed = |c: char| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-' | '!' | ';');
    id.chars().all(allowed)
        && id.chars().any(|c| c.is_ascii_alphabetic())
        && !id
            .to_ascii_lowercase()
            .starts_with("microsoft.autogenerated.")
        && !id.to_ascii_lowercase().ends_with(".exe")
}

/// A program path as the Start menu reports it: `{known-folder GUID}\...\x.exe`
/// (e.g. `{6D809377-...}\Notepad++\notepad++.exe`, the Program Files folder)
/// or `X:\...\x.exe`. Absolute, no `..`, no scheme, no UNC.
fn is_exe_target(id: &str) -> bool {
    if !id.to_ascii_lowercase().ends_with(".exe") {
        return false;
    }
    let rest = if let Some(rest) = id.strip_prefix('{') {
        match rest.split_once("}\\") {
            Some((guid, rest)) if is_guid(guid) => rest,
            _ => return false,
        }
    } else {
        let mut chars = id.chars();
        match (chars.next(), chars.next(), chars.next()) {
            (Some(drive), Some(':'), Some('\\')) if drive.is_ascii_alphabetic() => &id[3..],
            _ => return false,
        }
    };
    !rest.is_empty()
        && !rest.contains(['/', ':', '<', '>', '"', '|', '?', '*'])
        && !rest
            .split('\\')
            .any(|part| part.is_empty() || part == ".." || part == ".")
}

fn is_guid(text: &str) -> bool {
    let parts: Vec<&str> = text.split('-').collect();
    parts.len() == 5
        && parts
            .iter()
            .zip([8, 4, 4, 4, 12])
            .all(|(part, len)| part.len() == len && part.chars().all(|c| c.is_ascii_hexdigit()))
}

/// Words of a name that mark maintenance, not an app to use: uninstallers and
/// "reset preferences" / repair entries.
const MAINTENANCE_WORDS: [&str; 8] = [
    "uninstall",
    "uninstaller",
    "desinstalar",
    "desinstalador",
    "reset",
    "restablecer",
    "repair",
    "reparar",
];

fn has_maintenance_word(normalized: &str) -> bool {
    normalized
        .split(' ')
        .any(|word| MAINTENANCE_WORDS.contains(&word))
}

/// An uninstaller or maintenance entry: any word of the name, or the AppID
/// (`...\Uninstall.exe`, `...\unins000.exe`). Never started by `open_app`.
pub fn is_maintenance(entry: &AppEntry) -> bool {
    let id = entry.id.to_lowercase();
    let file = id.rsplit('\\').next().unwrap_or(&id);
    has_maintenance_word(&normalize(&entry.name))
        || id.contains("uninstall")
        || file.starts_with("unins")
}

fn is_usable(entry: &AppEntry) -> bool {
    !entry.name.is_empty() && is_launchable_id(&entry.id) && !is_maintenance(entry)
}

/// Index of a `Get-StartApps | ConvertTo-Json` output (an array, or a single
/// object when the list has one entry). Only launchable apps are kept
/// ([`is_launchable_id`]) and uninstallers and maintenance entries are dropped
/// ([`is_maintenance`]); so are entries with an empty name or control
/// characters in the AppID. An index with no usable entry is an error: it must
/// not make the adapter "ready".
pub fn parse_start_apps(output: &str) -> Result<Vec<AppEntry>, String> {
    let text = output.trim_start_matches('\u{feff}').trim();
    let value: serde_json::Value = serde_json::from_str(text)
        .map_err(|why| format!("unreadable Get-StartApps output: {why}"))?;
    let items = match value {
        serde_json::Value::Array(items) => items,
        object @ serde_json::Value::Object(_) => vec![object],
        _ => return Err("Get-StartApps output is neither a list nor an app".into()),
    };
    let entries: Vec<AppEntry> = items
        .iter()
        .filter_map(|item| {
            let name = item.get("Name")?.as_str()?.trim();
            let id = item.get("AppID")?.as_str()?.trim();
            let entry = AppEntry {
                name: name.to_string(),
                id: id.to_string(),
            };
            (!id.chars().any(char::is_control) && is_usable(&entry)).then_some(entry)
        })
        .collect();
    if entries.is_empty() {
        return Err("Get-StartApps listed no launchable app".into());
    }
    Ok(entries)
}

/// The Latin letters with a diacritic that Spanish and English names use,
/// folded to their base letter.
fn fold(c: char) -> char {
    match c {
        'á' | 'à' | 'ä' | 'â' | 'ã' | 'å' => 'a',
        'é' | 'è' | 'ë' | 'ê' => 'e',
        'í' | 'ì' | 'ï' | 'î' => 'i',
        'ó' | 'ò' | 'ö' | 'ô' | 'õ' => 'o',
        'ú' | 'ù' | 'ü' | 'û' => 'u',
        'ñ' => 'n',
        'ç' => 'c',
        other => other,
    }
}

/// Lower-cased, accent-free, letters and digits only, single spaces.
pub fn normalize(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars().flat_map(char::to_lowercase).map(fold) {
        if c.is_alphanumeric() {
            out.push(c);
        } else if !out.ends_with(' ') && !out.is_empty() {
            out.push(' ');
        }
    }
    out.truncate(out.trim_end().len());
    out
}

/// A query shorter than this (after normalising) is too vague to guess from.
const MIN_QUERY_CHARS: usize = 2;
/// Typos are only forgiven in names this long: "calculater" yes, "ab" no.
const MIN_TYPO_CHARS: usize = 5;

/// Below this many characters a query is matched only as a whole name or a
/// whole word of a name: "log" must not open "Logitech G Hub" because it is
/// its prefix. From this length a prefix is specific enough ("edge", "spot").
const MIN_PREFIX_CHARS: usize = 4;

/// Edit distance, giving up once it is certain to exceed `max`.
fn distance(a: &str, b: &str, max: usize) -> Option<usize> {
    let (a, b): (Vec<char>, Vec<char>) = (a.chars().collect(), b.chars().collect());
    if a.len().abs_diff(b.len()) > max {
        return None;
    }
    let mut previous: Vec<usize> = (0..=b.len()).collect();
    for (i, ca) in a.iter().enumerate() {
        let mut current = vec![i + 1];
        for (j, cb) in b.iter().enumerate() {
            let substitution = previous[j] + usize::from(ca != cb);
            current.push(substitution.min(previous[j + 1] + 1).min(current[j] + 1));
        }
        previous = current;
    }
    let result = previous[b.len()];
    (result <= max).then_some(result)
}

fn contains_words(haystack: &str, needle: &str) -> bool {
    format!(" {haystack} ").contains(&format!(" {needle} "))
}

/// How well `name` answers `query` (both normalised), higher is better.
fn score(name: &str, query: &str) -> Option<usize> {
    let extra = name.chars().count().abs_diff(query.chars().count()).min(99);
    if name == query {
        return Some(1000);
    }
    if query.chars().count() < MIN_PREFIX_CHARS {
        if contains_words(name, query) {
            return Some(700 - extra);
        }
        // Still allowed: the model wrapped a known name ("vlc app").
        if name.chars().count() >= 3 && contains_words(query, name) {
            return Some(500 + name.chars().count().min(99));
        }
        return None;
    }
    if name.starts_with(query) {
        return Some(800 - extra);
    }
    if contains_words(name, query) {
        return Some(700 - extra);
    }
    let name_words: Vec<&str> = name.split(' ').collect();
    if query
        .split(' ')
        .all(|word| name_words.iter().any(|w| w.starts_with(word)))
    {
        return Some(600 - extra);
    }
    // The model wrapped the name in more words: "spotify app".
    if name.chars().count() >= 3 && contains_words(query, name) {
        return Some(500 + name.chars().count().min(99));
    }
    let length = query.chars().count();
    if length >= MIN_TYPO_CHARS {
        let allowed = if length <= 7 { 1 } else { 2 };
        let closest = std::iter::once(name)
            .chain(name_words.iter().copied())
            .filter(|candidate| candidate.chars().count() >= MIN_TYPO_CHARS)
            .filter_map(|candidate| distance(query, candidate, allowed))
            .min();
        if let Some(d) = closest {
            return Some(300 - d * 10);
        }
    }
    None
}

/// Score of a whole-name match.
const EXACT: usize = 1000;
/// Score of a name that only equals the query once its `+` or `#` are dropped:
/// "notepad" is not a name for "Notepad++".
const EXACT_BUT_FOR_SYMBOLS: usize = 950;

/// [`normalize`], keeping the symbols that tell two apps apart.
fn spelled(text: &str) -> String {
    normalize(&text.replace('+', " plus ").replace('#', " sharp "))
}

/// The best entry for what the model called the app, or `None`. An entry is
/// scored against the query, and counts as a whole-name match when it is spelled
/// exactly as a term of the query's alias group ([`aliases::alias_terms`]). An
/// alias never gets a prefix or typo match: "fotos" must not open Photoshop
/// through "photos". The choice does not depend on the order of the menu: ties
/// go to the entry the query itself fits best, then to the shorter name, then to
/// name and id.
pub fn find_app<'a>(entries: &'a [AppEntry], raw_query: &str) -> Option<&'a AppEntry> {
    let query = normalize(raw_query);
    if query.chars().count() < MIN_QUERY_CHARS {
        return None;
    }
    // open_app has no confirmation: a request for an uninstaller or a reset is
    // not served, and must not fall through to the app it names.
    if has_maintenance_word(&query) {
        return None;
    }
    let asked = spelled(raw_query);
    let terms = aliases::alias_terms(&query);
    entries
        .iter()
        .filter_map(|entry| {
            let name = normalize(&entry.name);
            if name.is_empty() || is_maintenance(entry) {
                return None;
            }
            let name_spelled = spelled(&entry.name);
            // How well the model's own words fit, before any alias.
            let direct = score(&name, &query).map(|fit| {
                if fit == EXACT && name_spelled != asked {
                    EXACT_BUT_FOR_SYMBOLS
                } else {
                    fit
                }
            });
            let alias = terms
                .iter()
                .any(|term| name_spelled == *term)
                .then_some(EXACT);
            Some((direct.max(alias)?, direct, entry))
        })
        .max_by(|(a_score, a_direct, a), (b_score, b_direct, b)| {
            a_score
                .cmp(b_score)
                .then_with(|| a_direct.cmp(b_direct))
                .then_with(|| b.name.chars().count().cmp(&a.name.chars().count()))
                .then_with(|| b.name.cmp(&a.name))
                .then_with(|| b.id.cmp(&a.id))
        })
        .map(|(_, _, entry)| entry)
}

/// What `ShellExecuteExW` is given for an entry: the Apps folder item of its
/// indexed AppID (works for Store apps and desktop apps alike).
pub fn launch_target(entry: &AppEntry) -> String {
    format!(r"shell:AppsFolder\{}", entry.id)
}

