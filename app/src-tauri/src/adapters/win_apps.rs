fn lock<T>(mutex: &Mutex<T>) -> std::sync::MutexGuard<'_, T> {
    mutex
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner())
}

/// Wakes the background refresher: after a miss, or at the periodic tick.
#[derive(Default)]
pub struct RefreshSignal {
    wanted: Mutex<bool>,
    changed: Condvar,
}

impl RefreshSignal {
    /// Asks for a rebuild. Requests do not pile up: one is pending at most.
    pub fn request(&self) {
        *lock(&self.wanted) = true;
        self.changed.notify_all();
    }

    /// Waits up to `timeout` for a request; `true` if one arrived (and is
    /// consumed), `false` on the timeout.
    pub fn wait(&self, timeout: Duration) -> bool {
        let guard = lock(&self.wanted);
        let (mut guard, _) = self
            .changed
            .wait_timeout_while(guard, timeout, |wanted| !*wanted)
            .unwrap_or_else(|poisoned| poisoned.into_inner());
        std::mem::take(&mut *guard)
    }
}

/// The app index and its readiness.
#[derive(Default)]
pub struct AppIndex {
    entries: Mutex<Option<Vec<AppEntry>>>,
    pub refresh: RefreshSignal,
}

impl AppIndex {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn is_ready(&self) -> bool {
        lock(&self.entries).is_some()
    }

    /// Rebuilds from `source`. A failure keeps the previous index (or leaves it
    /// not ready) and reports why. Whatever the source, only launchable apps
    /// get in ([`is_launchable_id`], [`is_maintenance`]).
    pub fn refresh_from(&self, source: &dyn AppSource) -> Result<usize, String> {
        let entries: Vec<AppEntry> = source.list()?.into_iter().filter(is_usable).collect();
        if entries.is_empty() {
            return Err("the source listed no launchable app".into());
        }
        let count = entries.len();
        *lock(&self.entries) = Some(entries);
        Ok(count)
    }
}

/// `open_app` over an index and a launcher.
pub struct Apps {
    index: Arc<AppIndex>,
    launcher: Arc<dyn Launcher>,
}

impl Apps {
    pub fn new(index: Arc<AppIndex>, launcher: Arc<dyn Launcher>) -> Self {
        Apps { index, launcher }
    }

    /// Starts the app the model named and returns the display name of the
    /// entry that was launched (the reply says what really opened, not what
    /// the model called it). Returns as soon as Windows accepted the launch: it
    /// does not wait for a window. `NotReady` before the first index exists;
    /// `NotFound` (and a background refresh) on a miss.
    pub fn open(&self, name: &str) -> Result<String, PcError> {
        // The index lock is released before the (slow) launch.
        let found = {
            let entries = lock(&self.index.entries);
            let entries = entries.as_ref().ok_or(PcError::NotReady)?;
            find_app(entries, name).map(|entry| (launch_target(entry), entry.name.clone()))
        };
        let Some((target, launched)) = found else {
            self.index.refresh.request();
            return Err(PcError::NotFound);
        };
        self.launcher
            .launch(&target)
            .map(|()| launched)
            .map_err(PcError::Failed)
    }
}

/// A process as the ToolHelp snapshot reports it, with its id (the window
/// closer needs it to find the process's windows; the core never sees it).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ProcessEntry {
    pub pid: u32,
    pub exe_name: String,
    pub in_user_session: bool,
}

impl ProcessEntry {
    /// What the core is given: the name and the session flag, no id.
    pub fn info(&self) -> ProcessInfo {
        ProcessInfo {
            exe_name: self.exe_name.clone(),
            in_user_session: self.in_user_session,
        }
    }
}

/// A process as the ToolHelp snapshot reports it. `session` / `own` are
/// Windows session ids; a process counts as the user's only when both are
/// known and equal (unknown fails closed).
pub fn process_entry(
    pid: u32,
    exe: &[u16],
    session: Option<u32>,
    own: Option<u32>,
) -> ProcessEntry {
    let end = exe.iter().position(|&c| c == 0).unwrap_or(exe.len());
    ProcessEntry {
        pid,
        exe_name: String::from_utf16_lossy(&exe[..end]),
        in_user_session: matches!((session, own), (Some(a), Some(b)) if a == b),
    }
}

/// [`process_entry`] without the id.
pub fn process_info(exe: &[u16], session: Option<u32>, own: Option<u32>) -> ProcessInfo {
    process_entry(0, exe, session, own).info()
}

